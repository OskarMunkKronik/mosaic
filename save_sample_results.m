        "sample_name",...
        "Options",...
        "peak_borders",...
        "sum_elution_profile",...
        "Z_feature",...
        "allPeaks",...
        "clusters",....
        "cosMat_combined",...
        "mzroi",...
        'mass_spectra')
end 